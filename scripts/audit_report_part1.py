class TocDocTemplate(SimpleDocTemplate):
    def afterFlowable(self, flowable):
        if hasattr(flowable, 'bookmark_name'):
            level = getattr(flowable, 'bookmark_level', 0)
            text = getattr(flowable, 'bookmark_text', '')
            key = getattr(flowable, 'bookmark_key', '')
            self.notify('TOCEntry', (level, text, self.page, key))


def add_heading(text, style, level=0):
    """Create a heading paragraph with TOC bookmark."""
    key = f'h_{hashlib.md5(text.encode()).hexdigest()[:8]}'
    p = Paragraph(f'<a name="{key}"/>{text}', style)
    p.bookmark_name = key
    p.bookmark_level = level
    p.bookmark_text = text
    p.bookmark_key = key
    return p


def bullet_list(items, style=None):
    """Convert a list of strings into bullet paragraphs."""
    style = style or STYLES['bullet']
    return [Paragraph(f"• {item}", style) for item in items]


def two_col_score_row(label, score, max_score=10):
    """A two-column row showing a label and its score."""
    score_color = SEM_ERROR if score < 5 else (SEM_WARNING if score < 7 else (SEM_SUCCESS if score >= 8 else ACCENT))
    score_text = f'<font color="{score_color.hexval()}"><b>{score}</b></font><font color="{TEXT_MUTED.hexval()}">/{max_score}</font>'
    table = Table(
        [[Paragraph(label, STYLES['body_left']),
          Paragraph(score_text, ParagraphStyle('Score', parent=STYLES['body_left'], alignment=TA_RIGHT))]],
        colWidths=[CONTENT_W * 0.75, CONTENT_W * 0.25],
    )
    table.setStyle(TableStyle([
        ('VALIGN', (0, 0), (-1, -1), 'MIDDLE'),
        ('BOTTOMPADDING', (0, 0), (-1, -1), 5),
        ('TOPPADDING', (0, 0), (-1, -1), 5),
        ('LINEBELOW', (0, 0), (-1, -1), 0.3, BORDER),
        ('BACKGROUND', (0, 0), (-1, -1), colors.white),
    ]))
    return table


def findings_table(rows, col_widths=None):
    """Build a table with a header row and zebra striping.
    rows: list of lists (first row is header)
    """
    if col_widths is None:
        n = len(rows[0])
        col_widths = [CONTENT_W / n] * n

    # Wrap cell text in Paragraphs for word-wrap
    wrapped = []
    for r_idx, row in enumerate(rows):
        wrapped_row = []
        for c_idx, cell in enumerate(row):
            if isinstance(cell, Paragraph):
                wrapped_row.append(cell)
            else:
                if r_idx == 0:
                    # Header
                    wrapped_row.append(Paragraph(
                        f"<b>{cell}</b>",
                        ParagraphStyle('ThCell', fontName=DISPLAY_FONT_BOLD,
                                       fontSize=9, leading=12,
                                       textColor=colors.white, alignment=TA_LEFT)
                    ))
                else:
                    wrapped_row.append(Paragraph(
                        str(cell),
                        ParagraphStyle('TdCell', fontName=BODY_FONT,
                                       fontSize=8.5, leading=12,
                                       textColor=TEXT_PRIMARY, alignment=TA_LEFT)
                    ))
        wrapped.append(wrapped_row)

    t = Table(wrapped, colWidths=col_widths, repeatRows=1)
    style = [
        ('BACKGROUND', (0, 0), (-1, 0), HEADER_FILL),
        ('TEXTCOLOR', (0, 0), (-1, 0), colors.white),
        ('VALIGN', (0, 0), (-1, -1), 'TOP'),
        ('LEFTPADDING', (0, 0), (-1, -1), 6),
        ('RIGHTPADDING', (0, 0), (-1, -1), 6),
        ('TOPPADDING', (0, 0), (-1, -1), 6),
        ('BOTTOMPADDING', (0, 0), (-1, -1), 6),
        ('GRID', (0, 0), (-1, -1), 0.3, BORDER),
    ]
    # Zebra striping
    for i in range(1, len(rows)):
        if i % 2 == 0:
            style.append(('BACKGROUND', (0, i), (-1, i), TABLE_STRIPE))
        else:
            style.append(('BACKGROUND', (0, i), (-1, i), colors.white))
    t.setStyle(TableStyle(style))
    return t


