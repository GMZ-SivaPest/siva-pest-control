class ScoreCard(Flowable):
    """A small card showing a score and label."""
    def __init__(self, label, score, total="/10", color=ACCENT, width=55*mm, height=22*mm):
        Flowable.__init__(self)
        self.label = label
        self.score = score
        self.total = total
        self.color = color
        self.width = width
        self.height = height

    def draw(self):
        c = self.canv
        # Background
        c.setFillColor(CARD_BG)
        c.setStrokeColor(BORDER)
        c.setLineWidth(0.5)
        c.roundRect(0, 0, self.width, self.height, 4, fill=1, stroke=1)
        # Label
        c.setFillColor(TEXT_MUTED)
        c.setFont(DISPLAY_FONT_BOLD, 7.5)
        c.drawString(6, self.height - 8, self.label.upper())
        # Score
        c.setFillColor(self.color)
        c.setFont(DISPLAY_FONT, 18)
        c.drawString(6, 5, str(self.score))
        # Total suffix
        score_w = c.stringWidth(str(self.score), DISPLAY_FONT, 18)
        c.setFillColor(TEXT_MUTED)
        c.setFont(BODY_FONT, 9)
        c.drawString(6 + score_w + 2, 7, self.total)


class CalloutBox(Flowable):
    """A colored callout box with title + body."""
    def __init__(self, title, body, kind='info', width=CONTENT_W):
        Flowable.__init__(self)
        self.title = title
        self.body = body
        self.kind = kind
        self.width = width
        # Compute height based on wrapped text
        self.title_p = Paragraph(f"<b>{title}</b>", STYLES['callout_title'])
        self.body_p = Paragraph(body, STYLES['callout_body'])
        # Measure
        from reportlab.lib.styles import ParagraphStyle
        temp_w = width - 16
        self._title_w, self._title_h = self.title_p.wrap(temp_w, 1000)
        self._body_w, self._body_h = self.body_p.wrap(temp_w, 1000)
        self.height = self._title_h + self._body_h + 18

    def draw(self):
        c = self.canv
        # Background color by kind
        if self.kind == 'critical':
            bg = SEM_ERROR
            border = colors.HexColor('#C4482A')
        elif self.kind == 'warning':
            bg = SEM_WARNING
            border = colors.HexColor('#D4A957')
        elif self.kind == 'success':
            bg = SEM_SUCCESS
            border = colors.HexColor('#6BA078')
        else:  # info
            bg = SEM_INFO
            border = colors.HexColor('#6E8AAA')

        # Rounded background
        c.setFillColor(bg)
        c.setStrokeColor(border)
        c.setLineWidth(0.5)
        c.roundRect(0, 0, self.width, self.height, 4, fill=1, stroke=1)

        # Left accent bar
        c.setFillColor(colors.white)
        c.rect(0, 0, 3, self.height, fill=1, stroke=0)

        # Draw title + body
        self.title_p.drawOn(c, 8, self.height - 8 - self._title_h)
        self.body_p.drawOn(c, 8, 8)


